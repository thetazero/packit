/**
 * Deterministic 32-bit PRNG (mulberry32). Both sender and receiver derive a
 * packet's degree and block indices from the same seed, so this must produce
 * identical sequences on every platform.
 */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
